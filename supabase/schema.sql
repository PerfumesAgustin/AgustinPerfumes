create or replace function public.create_order(
  p_reseller_name text,
  p_phone text,
  p_notes text,
  p_items jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_order_id uuid := gen_random_uuid();
  v_order_number text;
  v_order_sequence bigint;
  v_total integer := 0;
  v_item jsonb;
  v_product public.products%rowtype;
  v_quantity integer;
begin
  if char_length(trim(coalesce(p_reseller_name, ''))) < 2 then raise exception 'Nombre inválido'; end if;
  if char_length(trim(coalesce(p_phone, ''))) < 6 then raise exception 'Teléfono inválido'; end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'El pedido está vacío';
  end if;
  if jsonb_array_length(p_items) > 100 then raise exception 'El pedido supera el máximo de productos'; end if;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_quantity := (v_item->>'quantity')::integer;
    if v_quantity <= 0 then raise exception 'Cantidad inválida'; end if;
    select * into v_product from public.products
      where id = (v_item->>'product_id')::bigint and is_active;
    if not found then raise exception 'Producto no disponible'; end if;
    if v_quantity > v_product.stock then
      raise exception 'Stock insuficiente para %', v_product.name;
    end if;
    v_total := v_total + v_quantity;
  end loop;

  v_order_sequence := nextval('public.order_number_seq');
  v_order_number := lpad(v_order_sequence::text, greatest(4, char_length(v_order_sequence::text)), '0');
  insert into public.orders (id, order_number, reseller_name, phone, notes, total_units)
  values (v_order_id, v_order_number, trim(p_reseller_name), trim(p_phone), nullif(trim(p_notes), ''), v_total);

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    select * into v_product from public.products where id = (v_item->>'product_id')::bigint;
    insert into public.order_items (order_id, product_id, product_name, quantity)
    values (v_order_id, v_product.id, v_product.name, (v_item->>'quantity')::integer);
  end loop;

  return jsonb_build_object('id', v_order_id, 'order_number', v_order_number, 'total_units', v_total);
end;
$$;

create or replace function public.confirm_order(p_order_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_order public.orders%rowtype;
  v_item public.order_items%rowtype;
  v_before integer;
begin
  if not public.is_admin() then raise exception 'No autorizado'; end if;
  select * into v_order from public.orders where id = p_order_id for update;
  if not found then raise exception 'Pedido inexistente'; end if;
  if v_order.status <> 'pending' or v_order.stock_applied then raise exception 'El pedido ya fue procesado'; end if;

  for v_item in select * from public.order_items where order_id = p_order_id order by product_id
  loop
    select stock into v_before from public.products where id = v_item.product_id for update;
    if v_before < v_item.quantity then raise exception 'Stock insuficiente para %', v_item.product_name; end if;
    update public.products set stock = stock - v_item.quantity where id = v_item.product_id;
    insert into public.stock_movements
      (product_id, order_id, movement_type, quantity, stock_before, stock_after, reason, created_by)
    values
      (v_item.product_id, p_order_id, 'order_confirmed', -v_item.quantity, v_before, v_before - v_item.quantity,
       'Confirmación ' || v_order.order_number, auth.uid());
  end loop;

  update public.orders set status = 'confirmed', stock_applied = true, confirmed_at = now(), confirmed_by = auth.uid()
  where id = p_order_id;
end;
$$;

create or replace function public.set_order_status(p_order_id uuid, p_status public.order_status)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_order public.orders%rowtype;
  v_item public.order_items%rowtype;
  v_before integer;
begin
  if not public.is_admin() then raise exception 'No autorizado'; end if;
  if p_status not in ('rejected', 'cancelled') then raise exception 'Estado no permitido'; end if;
  select * into v_order from public.orders where id = p_order_id for update;
  if not found then raise exception 'Pedido inexistente'; end if;
  if v_order.status in ('rejected', 'cancelled') then raise exception 'El pedido ya fue procesado'; end if;
  if p_status = 'rejected' and v_order.status <> 'pending' then raise exception 'Solo se rechazan pedidos pendientes'; end if;

  if p_status = 'cancelled' and v_order.stock_applied then
    for v_item in select * from public.order_items where order_id = p_order_id order by product_id
    loop
      select stock into v_before from public.products where id = v_item.product_id for update;
      update public.products set stock = stock + v_item.quantity where id = v_item.product_id;
      insert into public.stock_movements
        (product_id, order_id, movement_type, quantity, stock_before, stock_after, reason, created_by)
      values
        (v_item.product_id, p_order_id, 'order_cancelled', v_item.quantity, v_before, v_before + v_item.quantity,
         'Cancelación ' || v_order.order_number, auth.uid());
    end loop;
  end if;

  update public.orders set status = p_status, stock_applied = false where id = p_order_id;
end;
$$;

create or replace function public.adjust_stock(p_product_id bigint, p_delta integer, p_reason text default null)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare v_before integer; v_after integer;
begin
  if not public.is_admin() then raise exception 'No autorizado'; end if;
  if p_delta = 0 then raise exception 'El ajuste no puede ser cero'; end if;
  select stock into v_before from public.products where id = p_product_id for update;
  if not found then raise exception 'Producto inexistente'; end if;
  v_after := v_before + p_delta;
  if v_after < 0 then raise exception 'El stock no puede quedar negativo'; end if;
  update public.products set stock = v_after where id = p_product_id;
  insert into public.stock_movements
    (product_id, movement_type, quantity, stock_before, stock_after, reason, created_by)
  values (p_product_id, case when p_delta > 0 then 'manual_add' else 'manual_remove' end,
          p_delta, v_before, v_after, p_reason, auth.uid());
  return v_after;
end;
$$;

create or replace function public.set_product_stock(p_product_id bigint, p_stock integer, p_reason text default null)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare v_before integer;
begin
  if not public.is_admin() then raise exception 'No autorizado'; end if;
  if p_stock < 0 then raise exception 'El stock no puede ser negativo'; end if;
  select stock into v_before from public.products where id = p_product_id for update;
  if not found then raise exception 'Producto inexistente'; end if;
  update public.products set stock = p_stock where id = p_product_id;
  insert into public.stock_movements
    (product_id, movement_type, quantity, stock_before, stock_after, reason, created_by)
  values (p_product_id, 'set', p_stock - v_before, v_before, p_stock, p_reason, auth.uid());
  return p_stock;
end;
$$;

