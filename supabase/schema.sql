create table if not exists public.admin_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'Administrador',
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) between 1 and 160),
  source_name text,
  gender public.product_gender not null default 'Sin clasificar',
  stock integer not null default 0 check (stock >= 0),
  min_stock integer not null default 3 check (min_stock >= 0),
  photo_url text,
  catalog_section text not null default 'extractos' check (catalog_section in ('extractos', 'tubitos_arabes')),
  is_active boolean not null default true,
  data_status text not null default 'revisar' check (data_status in ('foto_validada', 'revisar')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number text unique not null,
  reseller_name text not null check (char_length(trim(reseller_name)) between 2 and 120),
  phone text not null check (char_length(trim(phone)) between 6 and 40),
  notes text check (notes is null or char_length(notes) <= 1000),
  status public.order_status not null default 'pending',
  total_units integer not null check (total_units > 0),
  stock_applied boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  confirmed_at timestamptz,
  confirmed_by uuid references auth.users(id)
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint not null references public.products(id),
  product_name text not null,
  quantity integer not null check (quantity > 0),
  unique (order_id, product_id)
);

create table if not exists public.stock_movements (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id),
  order_id uuid references public.orders(id),
  movement_type text not null check (movement_type in ('manual_add', 'manual_remove', 'set', 'order_confirmed', 'order_cancelled')),
  quantity integer not null,
  stock_before integer not null check (stock_before >= 0),
  stock_after integer not null check (stock_after >= 0),
  reason text,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now()
);

create table if not exists public.business_settings (
  id boolean primary key default true check (id),
  business_name text not null default 'Perfume Stock · Agustín',
  whatsapp_number text not null default '5491167463767',
  default_min_stock integer not null default 3 check (default_min_stock >= 0),
  updated_at timestamptz not null default now()
);

insert into public.business_settings (id) values (true) on conflict (id) do nothing;

create index if not exists products_active_name_idx on public.products (is_active, name);
create index if not exists products_section_active_name_idx on public.products (catalog_section, is_active, name);
